package io.github.kilgoret.mate

import kotlin.reflect.KClass

/**
 * Исполнитель семейства эффектов. Handler декларирует семейство
 * ([effectFamily]) — раннер строит реестр «семейство → исполнитель»
 * и доставляет каждый эффект ровно одному handler'у.
 *
 * Нарушения роутинга — ошибки ([MateError]):
 * - два handler'а на одно семейство — fail при создании раннера;
 * - эффект без исполнителя — fail при диспатче (сирота);
 * - эффект, матчащийся на два семейства, — fail при диспатче:
 *   эффект принадлежит ровно одному семейству, вложенные
 *   family-декларации запрещены.
 *
 * Маршрутизация — только по типу эффекта; логика исполнения (кэш или
 * сеть, ретраи) живёт внутри исполнителя. Расширение (лог, метрики) —
 * декоратором handler'а, не вторым handler'ом.
 *
 * Результат исполнения возвращается в цикл НОВЫМ Message через
 * [runEffect]'s consumer — колбэков в обход цикла не существует.
 *
 * [Message] ковариантен: handler, не шлющий сообщений вовсе
 * (`MateEffectHandler<Nothing, …>`), совместим с раннером любого
 * Message-типа — так один shared-исполнитель (например, навигация)
 * встаёт в сборку каждого экрана приложения.
 */
public interface MateEffectHandler<out Message, E : Effect> {
    /** Семейство, которое этот handler исполняет. */
    public val effectFamily: KClass<E>

    public suspend fun runEffect(effect: E, consumer: (Message) -> Unit)
}
