package io.github.kilgoret.mate

import kotlinx.coroutines.flow.StateFlow

/** Публичный контракт раннера для UI: поток состояния + вход сообщений. */
public interface MateStore<State, Message> {
    /**
     * Единственный источник чтения состояния. Публикуется циклом
     * раннера после каждого reduce; все чтения — подпиской на поток.
     * Синхронное чтение `value` сразу после [accept] не определено:
     * сообщение обрабатывается конкурентно, чтение вернёт состояние
     * до или после обработки в зависимости от гонки с циклом.
     */
    public val state: StateFlow<State>

    /**
     * Вход сообщений в цикл. Не блокирует: сообщение встаёт в
     * FIFO-очередь раннера и обрабатывается асинхронно.
     */
    public fun accept(message: Message)
}
