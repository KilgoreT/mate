package io.github.kilgoret.mate

import kotlinx.coroutines.flow.Flow
import kotlin.reflect.KClass

/**
 * Корневой маркер ПОДПИСКИ — длящегося намерения, выводимого из State.
 *
 * Подписка — ТОЛЬКО данные (data-класс): лямбда или Flow-ссылка внутри
 * сломает equality-дифф. Идентичность подписки = equality её данных:
 * изменился параметр — это ДРУГАЯ подписка (старая гаснет, новая
 * стартует). Принудительный рестарт «той же» подписки выражается
 * различающим полем (generation) — это П1 в действии.
 *
 * Runtime сам диффит `subscriptions(state)` после каждого изменения
 * состояния: новые включает, исчезнувшие гасит. «Подвисшая подписка»
 * невозможна по построению; teardown — исчезновение из набора
 * (elm-семантика Sub).
 */
public interface Sub

/**
 * Исполнитель СЕМЕЙСТВА подписок: по данным подписки строит поток
 * Message. Зеркало [MateEffectHandler] для длящихся намерений.
 *
 * Правила роутинга — те же и такие же громкие: один handler на
 * семейство (дубль — fail на создании раннера), подписка-сирота и
 * двойной матч — fail при диффе.
 *
 * Ошибки потока — прежде всего обязанность фабрики (`catch` → Msg-fail,
 * как конвенция «Msg подписки несёт параметры Sub»); необработанное
 * исключение гасит ЭТУ подписку (без рестарта), уходит в
 * [MateObserver.onSubscriptionError] и [MateFailPolicy].
 */
public interface MateSubscriptionHandler<Message, S : Sub> {
    /** Семейство подписок, которое этот handler исполняет. */
    public val subFamily: KClass<S>

    /** Построить поток Message по данным подписки. */
    public fun flow(sub: S): Flow<Message>
}
