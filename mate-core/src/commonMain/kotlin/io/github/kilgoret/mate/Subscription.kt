package io.github.kilgoret.mate

import kotlinx.coroutines.flow.Flow
import kotlin.reflect.KClass

/**
 * Корневой тип подписки. Подписка — постоянный источник Message,
 * выводимый из State (Flow из БД, тикер, системные события): пока
 * состояние объявляет подписку, её поток жив и его сообщения
 * приходят в цикл.
 *
 * Подписка — только данные (data-класс): лямбда или Flow-ссылка
 * внутри сломает equality-дифф. Идентичность подписки — equality её
 * данных: изменился параметр — это другая подписка, старая гаснет,
 * новая стартует. Принудительный рестарт «той же» подписки выражается
 * различающим полем (generation).
 *
 * Раннер диффит `subscriptions(state)` после каждого изменения
 * состояния: новые включает, исчезнувшие гасит. Подвисшая подписка
 * невозможна по построению; teardown — исчезновение из набора.
 */
public interface Subscription

/**
 * Исполнитель семейства подписок: по данным подписки строит поток
 * Message. Зеркало [MateEffectHandler] для постоянных источников.
 *
 * Правила роутинга те же ([MateError]): один handler на семейство
 * (дубль — fail при создании раннера), подписка-сирота и двойной
 * матч — fail при диффе.
 *
 * Ошибки потока обрабатывает фабрика потока (`catch` → Msg об ошибке
 * с параметрами подписки); необработанное исключение гасит эту
 * подписку без рестарта и уходит в [MateObserver.onSubscriptionError]
 * и [MateFailPolicy].
 */
public interface MateSubscriptionHandler<Message, S : Subscription> {
    /** Семейство подписок, которое этот handler исполняет. */
    public val subscriptionFamily: KClass<S>

    /** Построить поток Message по данным подписки. */
    public fun flow(sub: S): Flow<Message>
}
